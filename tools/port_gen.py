"""Translate the staged game sources for the SDL3 port (docs/sdl3-port.md).

Input: the compile plan and translation units `tools/game_build.py` stages for the Amiga build
(build/game/compile-plan.json, guest_source/) - the exact code the verified Amiga build compiles.
Output: build/port-gen/<unit>.c (never committed), compiled by port/CMakeLists.txt.

The C stays Aztec C 3.6; only its data model is made explicit for a 32-bit host:
  int, short -> int16_t; unsigned (int/short) -> uint16_t; long -> int32_t;
  unsigned long -> uint32_t; an implicit-int function definition returns int16_t;
  structures keep the 68000's 2-byte alignment (#pragma pack(2)).
Units that need a port version (inline #asm, hardware through raw pointers) are listed
in the report; port/override/<unit>.c replaces such a unit when present.

Usage: python tools/port_gen.py [--source DIR] [--output DIR] [--override-dir DIR]
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = '#include "aztec.h"\n#pragma pack(push, 2)\n'
FOOTER = '\n#pragma pack(pop)\n'

TOKEN = re.compile(r'''
    (?P<comment>/\*.*?\*/|//[^\n]*)
  | (?P<string>"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*')
  | (?P<word>[A-Za-z_]\w*)
  | (?P<space>\s+)
  | (?P<other>.)
''', re.S | re.X)

INTEGER_WORDS = {'int', 'short', 'long', 'unsigned', 'signed'}
HARDWARE = re.compile(r'0x(?:dff|bfe|bfd)[0-9a-f]{3}\b', re.I)


def tokens(text):
    return [(m.lastgroup, m.group()) for m in TOKEN.finditer(text)]


def integer_type(words):
    """The fixed-width type of an Aztec integer specifier sequence."""
    unsigned = 'unsigned' in words
    if 'long' in words:
        return 'uint32_t' if unsigned else 'int32_t'
    if 'char' in words:
        return 'unsigned char' if unsigned else ('signed char' if 'signed' in words else 'char')
    return 'uint16_t' if unsigned else 'int16_t'


def translate_types(text):
    """Replace each maximal run of integer specifier words (char included when it
    follows unsigned/signed) by its fixed-width type, outside comments and strings."""
    out, toks, i = [], tokens(text), 0
    while i < len(toks):
        kind, value = toks[i]
        if kind == 'word' and value in INTEGER_WORDS:
            words, j, last = [value], i + 1, i
            while j < len(toks):
                k, v = toks[j]
                if k == 'space':
                    j += 1; continue
                if k == 'word' and (v in INTEGER_WORDS or (v == 'char' and words[-1] in ('unsigned', 'signed'))):
                    words.append(v); last = j; j += 1; continue
                break
            out.append(integer_type(words)); i = last + 1; continue
        out.append(value); i += 1
    return ''.join(out)


IMPLICIT_DEFINITION = re.compile(r'^(?P<name>[A-Za-z_]\w*)\s*\((?P<params>[^;{}]*)\)\s*(?=$|\n)', re.M)


TYPE_TAIL = re.compile(r'(?:\b(?:char|void|int16_t|uint16_t|int32_t|uint32_t|float|double|struct\s+\w+|union\s+\w+)|\*)\s*$')
KEYWORDS = {'if', 'while', 'for', 'switch', 'return', 'sizeof'}


def explicit_returns(text):
    """`name(params)` at the start of a line, followed by K&R parameter declarations or a
    body, is an implicit-int definition in Aztec: 16 bits. A return type written on the
    line before stays as it is. Returns (text, names) - names get forward declarations,
    because a call before the definition would otherwise imply a 32-bit int."""
    names = []

    def fix(m):
        rest = text[m.end():m.end() + 400]
        before = text[:m.start()].rstrip()
        if (m.group('name') in KEYWORDS or TYPE_TAIL.search(before)
                or not re.match(r'\s*(\{|[A-Za-z_][\w\s\*,\[\]]*;)', rest)):
            return m.group(0)
        names.append(m.group('name'))
        return 'int16_t ' + m.group(0)
    return IMPLICIT_DEFINITION.sub(fix, text), names


# Aztec runtime globals whose names the host C library reserves (errno is a macro there);
# the port's runtime provides them under these names. The game's main is called by the
# port's launcher.
RUNTIME_RENAMES = {'errno': 'aztec_errno', 'main': 'game_main'}


def translate_materialization(guest):
    """GNU as (i686) for the Amiga build's link-materialization symbol aliases. The
    measured BSS reservations are laid out in the DATA hunk (generate_data_hunk); the JMP
    bridges that rebind C `exit` are not carried over: the port keeps the host's exit."""
    lines = ['# generated by tools/port_gen.py from the Amiga build materialization']
    for line in (guest / 'LINK_MATERIALIZATION/data_aliases.asm').read_text(encoding='latin-1').splitlines():
        m = re.match(r'(\S+)\s+equ\s+(\S+)', line)
        if m:
            lines += ['\t.globl %s' % m.group(1), '\t.set %s, %s' % (m.group(1), m.group(2))]
    return '\n'.join(lines) + '\n'


PROVIDER = re.compile(r'staged accepted DATA provider: (\S+?);')
DEFINITION = re.compile(r'^(?P<type>(?:struct\s+\w+|union\s+\w+|[A-Za-z_]\w*)(?:\s+[A-Za-z_]\w*)*[\s\*]*?)\s*'
                        r'(?P<name>(?:G_h01_[0-9A-F]{4}|LINK_ONLY_GAP_\w+))\s*(?P<dims>(?:\[[^\]]*\]\s*)*)=', re.M)
SYMBOL = re.compile(r'(&\s*)?\bG_h01_([0-9A-F]{4})\b')


def initializer_end(text, start):
    """Index of the `;` that ends an initializer starting at `start`."""
    depth, i = 0, start
    while i < len(text):
        c = text[i]
        if c in '"\'':
            i += 1
            while i < len(text) and text[i] != c:
                i += 2 if text[i] == '\\' else 1
        elif c in '{(':
            depth += 1
        elif c in '})':
            depth -= 1
        elif c == ';' and depth == 0:
            return i
        i += 1
    raise ValueError('unterminated initializer')


def provider_unit(text, suffix):
    """(declarations, definitions, externs) of a staged DATA provider unit. Struct tags
    and typedef names get `suffix`, so units with equal tag names can share one file."""
    text = translate_types(text)
    macros = dict(re.findall(r'^#define (\w+) (\w+)$', text, re.M))
    tags = (set(re.findall(r'\b(?:struct|union)\s+(\w+)\s*\{', text))
            | set(re.findall(r'\btypedef\b[^;]*?\(\s*\*\s*(\w+)\s*\)', text))          # typedef T (*Name)(...);
            | set(re.findall(r'\btypedef\b[^;(]*?\b(\w+)\s*(?:\[[^\]]*\]\s*)*;', text)))   # typedef T Name;
    out = []
    for kind, value in tokens(text):
        if kind == 'word':
            value = macros.get(value, value)
            value = value + suffix if value in tags else value
        out.append(value)
    text = re.sub(r'^#define .*$', '', ''.join(out), flags=re.M)
    definitions, spans = [], []
    for m in DEFINITION.finditer(text):
        end = initializer_end(text, m.end())
        spans.append((m.start(), end + 1))
        if m.group('name').startswith('G_h01_'):
            definitions.append(dict(name=m.group('name'), type=m.group('type').strip(), dims=m.group('dims').strip(),
                                    init=text[m.end():end].strip()))
    rest = text
    for start, end in reversed(spans):
        rest = rest[:start] + rest[end:]
    externs = re.findall(r'^\s*extern\s[^;]*;', rest, re.M)
    declarations = re.sub(r'^\s*extern\s[^;]*;', '', rest, flags=re.M)
    declarations = re.sub(r'/\*.*?\*/', '', declarations, flags=re.S).strip()
    return declarations, definitions, externs


def hunk_address(init):
    """References to DATA-hunk symbols in an initializer become addresses in the hunk."""
    return SYMBOL.sub(lambda m: 'HUNK(0x%s)' % m.group(2), init)


def generate_data_hunk(plan, guest, root=ROOT, moved=None):
    """The Amiga DATA hunk (initialized data and its BSS tail) as ONE packed structure:
    every typed DATA provider and every measured BSS reservation at its original offset,
    raw spans as zero bytes, every G_h01_XXXX name an alias into it. The game indexes
    across provider boundaries (G_h01_27E4[n] runs into G_h01_27E8 ...), so adjacency
    must be the Amiga's. `moved` (interior_aliases) places names that view part of a wider
    scalar at the host position of the same bits. Returns the C text."""
    moved = moved or {}
    ledger = json.loads((root / 'recovery/ledger.json').read_text())['data_providers']
    items, declarations, externs = [], [], {}
    for entry in plan:
        if entry['kind'] != 'c' or not Path(entry['object']).name.startswith('obj_data_'):
            continue
        text = (guest / entry['source']).read_text(encoding='latin-1')
        ids = PROVIDER.findall(text)
        decl, definitions, unit_externs = provider_unit(text, '_' + Path(entry['object']).stem[9:])
        declarations.append(decl)
        for line in unit_externs:
            if 'G_h01_' in line:
                continue
            name = re.findall(r'(\w+)\s*(?:\(\s*\)|\[\s*\])?\s*;', line)
            externs.setdefault(name[-1] if name else line, line.strip())
        bounds = {}
        for ident in ids:
            fact = json.loads((root / ledger[ident]['fact']).read_text())
            start, size = fact['original']['start'], fact['original']['size']
            offsets = sorted((start + d['offset'], d['symbol']) for d in fact['definitions'] if d.get('symbol'))
            for i, (offset, symbol) in enumerate(offsets):
                bounds['G_h01_' + symbol[-4:] if not symbol.startswith('G_h01_') else symbol] = \
                    (offset, (offsets[i + 1][0] if i + 1 < len(offsets) else start + size) - offset)
        for d in definitions:
            offset, size = bounds[d['name']]
            if offset != int(d['name'][6:], 16):
                raise ValueError('provider offset differs from its name: ' + d['name'])
            items.append(dict(d, offset=offset, size=size))
            PROVIDER_TYPES[d['name']] = d['type'].strip()
    for line in (guest / 'LINK_ONLY_STUBS/measured_reservations.asm').read_text(encoding='latin-1').splitlines():
        m = re.match(r'\s+bss\s+_(G_h01_([0-9A-F]{4}))\s*,\s*(\d+)', line)
        if m:
            items.append(dict(name=m.group(1), offset=int(m.group(2), 16), size=int(m.group(3)), type=None))
    items.sort(key=lambda d: (d['offset'], d['type'] is None))
    members, initializers, aliases, cursor = [], [], [], 0
    for d in items:
        aliases.append((d['name'], d['offset']))
        if d['offset'] < cursor:
            continue                               # inside an earlier member: an alias only
        if d['offset'] > cursor:
            members.append('    uint8_t gap_%04X[%d];' % (cursor, d['offset'] - cursor))
        member = 'm_%04X' % d['offset']
        if d['type'] is None:
            members.append('    uint8_t %s[%d];' % (member, d['size']))
        else:
            dims = d['dims']
            if dims.startswith('[]'):                # unsized: the provider's extent fixes it
                rest = dims[2:].strip()
                dims = '[%d / sizeof(%s%s)]%s' % (d['size'], d['type'], rest, rest)
            members.append('    union { %s v%s; uint8_t raw[%d]; } %s;' % (d['type'], dims, d['size'], member))
            initializers.append('    .%s = { .v = %s },' % (member, hunk_address(d['init'])))
        members.append('    /* %s */' % d['name'])
        cursor = d['offset'] + d['size']
    asserts = ['_Static_assert(offsetof(struct amiga_data_hunk, m_%04X) == 0x%X, "%s");' % (o, o, n)
               for n, o in aliases if ('m_%04X' % o) in '\n'.join(members) and n == 'G_h01_%04X' % o]
    alias_lines = ''.join('    ".globl _%s\\n.set _%s, _amiga_data_hunk+0x%X\\n"%s\n'
                          % (n, n, moved.get(n, o), ' /* big-endian +0x%X */' % o if n in moved else '')
                          for n, o in dict(aliases).items())
    return '\n'.join([
        '/* generated by tools/port_gen.py: the Amiga DATA hunk at its original layout. */',
        '#include "aztec.h"', '#pragma pack(push, 2)',
        '\n'.join(sorted(set(externs.values()))),
        '\n'.join(d for d in declarations if d),
        'struct amiga_data_hunk {', '\n'.join(members), '};',
        'extern struct amiga_data_hunk amiga_data_hunk;',
        '#define HUNK(o) ((void *)((char *)&amiga_data_hunk + (o)))',
        'struct amiga_data_hunk amiga_data_hunk = {', '\n'.join(initializers), '};',
        '\n'.join(asserts),
        '__asm__(\n' + alias_lines + ');',
        '#pragma pack(pop)', ''])


def rename_runtime(text):
    out = []
    for kind, value in tokens(text):
        out.append(RUNTIME_RENAMES.get(value, value) if kind == 'word' else value)
    return ''.join(out)


ALIAS = re.compile(r'^(#define (G_h01_[0-9A-F]{4}) \(?\*?\((?P<type>[\w\s]+?)\s*\*\)\(\(char \*\)&(?P<base>G_h01_[0-9A-F]{4}) \+ )(?P<offset>\d+)(\)\)\)?)$', re.M)
SCALAR_WIDTH = {'char': 1, 'signed char': 1, 'unsigned char': 1, 'int16_t': 2, 'uint16_t': 2, 'int32_t': 4, 'uint32_t': 4}
_MODEL = {}


PROVIDER_TYPES = {}                               # filled by generate_data_hunk: name -> element type


def base_element_width(base, root=ROOT):
    """Element width of a scalar (or scalar-array) DATA global: from its provider
    definition, else from the data model."""
    if base in PROVIDER_TYPES:
        return SCALAR_WIDTH.get(PROVIDER_TYPES[base])
    if not _MODEL:
        _MODEL.update(json.loads((root / 'recovery/data_model.json').read_text())['globals'])
    kind = translate_types(re.sub(r'\[.*$', '', str(_MODEL.get(base, {}).get('type', '')))).strip()
    return SCALAR_WIDTH.get(kind)


def byte_order_aliases(text):
    """A narrower view inside a big-endian scalar names different bytes on a
    little-endian host: the low byte of the 16-bit G_h01_0970 is at +1 on the 68000 and at
    +0 here. Such interior aliases are moved to the host position of the same value bits."""
    def fix(m):
        width = SCALAR_WIDTH.get(m.group('type').strip())
        element = base_element_width(m.group('base'))
        offset = int(m.group('offset'))
        if not width or not element or width >= element:
            return m.group(0)
        inside = offset % element
        return '%s%d%s /* big-endian +%d */' % (m.group(1), offset - inside + element - inside - width, m.group(6), offset)
    return ALIAS.sub(fix, text)


SCALAR_VIEW = re.compile(r'\(\(\s*(?P<type>(?:unsigned |signed )?char|u?int(?:16|32)_t)\s*\*\s*\)\s*&')


def closing(text, i, pair='()'):
    """Index of the bracket that closes the one at text[i]."""
    depth = 0
    for j in range(i, len(text)):
        if text[j] == pair[0]:
            depth += 1
        elif text[j] == pair[1]:
            depth -= 1
            if depth == 0:
                return j
    raise ValueError('unbalanced ' + pair)


def scalar_views(text, notes=None):
    """`((T *)&x)[k]` -> BE_VIEW(T, x, k) (port/include/aztec.h): an index into a narrower
    view of a scalar counts from the other end on a little-endian host."""
    pos = 0
    while True:
        m = SCALAR_VIEW.search(text, pos)
        if not m:
            return text
        close = closing(text, m.start())
        after = re.match(r'\s*\[', text[close + 1:])
        if not after or re.search(r'[-+*/]', text[m.end():close].replace('->', '')):   # an offset view: not a scalar
            pos = m.end(); continue
        bracket = close + after.end()
        end = closing(text, bracket, '[]')
        view = 'BE_VIEW(%s, %s, %s)' % (m.group('type'), text[m.end():close].strip(), text[bracket + 1:end].strip())
        if notes is not None:
            notes.append(dict(view=text[m.start():end + 1], rewritten=view))
        text = text[:m.start()] + view + text[end + 1:]
        pos = m.start() + len(view)


# Structures that name one byte of a big-endian word, reviewed once (docs/sdl3-port.md,
# byte order). The two byte members are swapped, so the named byte holds the same value bits
# on a little-endian host; the word views of the same storage stay as they are.
WORD_BYTE_PAIRS = {
    ('Cell', 'pad', 'bits'): 'ov10 cave cell: an int word (F_h10_0000 parses and tests it as one)',
    ('BoardCell', 'pad', 'bits'): 'ov10 cave cell word',
    ('Flags', 'pad', 'bits'): 'ov10 cave cell word',
    ('Flags', 'reserved', 'bits'): 'ov10 cave cell word (union with its int view)',
    ('Descriptor', 'pad4', 'state'): 'ov11 animation descriptor: word4 is an int (F_h11_15C8 stores it)',
    ('Holder', 'pad0', 'state'): 'ov11 animation descriptor (word4)',
    ('Source', 'pad0', 'value'): 'ov11 animation descriptor (word4)',
}
AGGREGATE = re.compile(r'\b(?:struct|union)\s+(\w+)\s*\{')


def swap_word_bytes(text, notes=None):
    for m in reversed(list(AGGREGATE.finditer(text))):
        end = closing(text, m.end() - 1, '{}')
        body = text[m.end():end]
        for (tag, first, second), why in WORD_BYTE_PAIRS.items():
            if tag != m.group(1):
                continue
            pair = re.compile(r'((?:unsigned |signed )?char\s+%s\s*;)(\s*)((?:unsigned |signed )?char\s+%s\s*;)' % (first, second))
            body, count = pair.subn(lambda p: '%s%s%s /* big-endian word: %s */' % (p.group(3), p.group(2), p.group(1), why), body)
            if count and notes is not None:
                notes.append(dict(aggregate=tag, swapped=[first, second]))
        text = text[:m.end()] + body + text[end:]
    return text


EXTERN_VIEW = re.compile(r'\bextern\s+(?P<type>[\w ]+?)\s*(?P<ptr>\**)\s*\b(?P<name>G_h01_[0-9A-F]{4})\s*(?P<dims>(?:\[[^\]]*\])*)\s*;')


def access_widths(texts):
    """DATA/BSS name -> the access widths of every unit that uses its value (not only its
    address): 0 for a structure or any other non-integer view. Byte arrays are storage."""
    widths = {}
    for text in texts:
        text = re.sub(r'/\*.*?\*/', '', translate_types(text), flags=re.S)
        body = EXTERN_VIEW.sub('', text)
        for m in EXTERN_VIEW.finditer(text):
            width = 4 if m.group('ptr') else SCALAR_WIDTH.get(m.group('type').strip(), 0)
            if m.group('dims') and width == 1:
                continue
            if any(not amp for amp in re.findall(r'(&\s*)?\b%s\b' % m.group('name'), body)):
                widths.setdefault(m.group('name'), set()).add(width)
    return widths


def interior_aliases(widths):
    """Names that view part of a wider scalar (the low byte G_h01_A9C3 of the 16-bit
    G_h01_A9C2): name -> the hunk offset of the same value bits on a little-endian host.
    Only names with one integer access width everywhere are moved."""
    scalars = {int(n[6:], 16): next(iter(w)) for n, w in widths.items() if len(w) == 1 and min(w) > 1}
    moved = {}
    for name, w in widths.items():
        if len(w) != 1 or 0 in w:
            continue
        width, offset = next(iter(w)), int(name[6:], 16)
        for base, element in scalars.items():
            if base < offset < base + element and width < element:
                moved[name] = base + element - (offset - base) - width
    return moved


def translate(text, notes=None):
    text = byte_order_aliases(translate_types(rename_runtime(text)))
    body, names = explicit_returns(swap_word_bytes(scalar_views(text, notes), notes))
    forward = ''.join('int16_t %s();\n' % name for name in dict.fromkeys(names))
    return HEADER + forward + body + FOOTER


def needs_override(text):
    reasons = []
    if re.search(r'^\s*#asm\b', text, re.M):
        reasons.append('inline #asm')
    if HARDWARE.search(''.join(v for k, v in tokens(text) if k != 'comment')):
        reasons.append('custom chip / CIA address')
    return reasons


STAGED_SOURCE = re.compile(r'staged from accepted source: (\S+?);')


def unit_override(text, override_dir):
    """port/override/<source stem>.c replaces a unit built from that one accepted source
    (keyed by source, not by the Amiga build's object number, which moves)."""
    sources = STAGED_SOURCE.findall(text)
    if not override_dir or len(sources) != 1:
        return None
    candidate = override_dir / (Path(sources[0]).stem + '.c')
    return candidate if candidate.is_file() else None


def generate(source, output, override_dir=None):
    """Translate every C unit of the Amiga build's compile plan; list its assembly units
    (each needs a port version: a CODE-data table, a reconstructed-assembly module or a
    link-materialization file)."""
    output.mkdir(parents=True, exist_ok=True)
    for stale in output.glob('*.c'):
        stale.unlink()
    plan = json.loads((source / 'compile-plan.json').read_text())
    guest = source / 'guest_source'
    game_units = [guest / e['source'] for e in plan
                  if e['kind'] == 'c' and not Path(e['object']).name.startswith('obj_data_')]
    widths = access_widths(p.read_text(encoding='latin-1') for p in game_units)
    moved = interior_aliases(widths)
    # The data hunk first: its provider types drive the byte-order alias rewrite.
    data_hunk = generate_data_hunk(plan, guest, moved=moved)
    # The reconstructed assembly and its tables (tools/asm_port.py): asm_code.c, asm_tables.c,
    # asm_symbols.s; the labels of table parts that live in the DATA hunk alias into it here.
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import asm_port
    asm_report = asm_port.generate(source, output, data_hunk)
    data_hunk += '__asm__(\n%s);\n' % ''.join('    ".globl %s\\n.set %s, _amiga_data_hunk+0x%X\\n"\n' % (l, l, at)
                                              for l, at in asm_report.pop('data_aliases'))
    (output / 'data_hunk.c').write_text(data_hunk, encoding='latin-1', newline='\n')
    report = dict(units=0, overridden=[], needs_override={}, assembly=[],
                  byte_order=dict(interior_names={n: '0x%X' % o for n, o in sorted(moved.items())},
                                  mixed_widths={n: sorted(w) for n, w in sorted(widths.items())
                                                if len(w) > 1 and 0 not in w},
                                  views={}),
                  asm=asm_report)
    for entry in plan:
        name = Path(entry['object']).stem + '.c'
        if entry['kind'] != 'c':
            report['assembly'].append(entry['source']); continue
        if name.startswith('obj_data_'):
            report['data_providers'] = report.get('data_providers', 0) + 1; continue   # in data_hunk.c
        text = (guest / entry['source']).read_text(encoding='latin-1')
        override = unit_override(text, override_dir)
        if override:
            target_text = override.read_text(encoding='utf-8'); report['overridden'].append(override.name)
        else:
            reasons = needs_override(text)
            if reasons:
                report['needs_override'][name] = reasons
            notes = []
            target_text = translate(text, notes)
            if notes:
                report['byte_order']['views'][name] = notes
        (output / name).write_text(target_text, encoding='latin-1', newline='\n')
        report['units'] += 1
    (output / 'materialization.s').write_text(translate_materialization(guest), encoding='latin-1', newline='\n')
    report['readable_names'] = readable_names(output)
    (output / 'port-gen-report.json').write_text(json.dumps(report, indent=1) + '\n', encoding='utf-8')
    return report


def readable_names(output):
    """The port reads like src/: every generated file spells the game's functions and globals
    with their recovery/names.json names (tools/names.py). Word level, string literals
    included - the `.set` aliases of data_hunk.c and asm_tables.c live in asm strings, and no
    game text contains a mechanical name. Runs last: the generation above needs mechanical
    names. Returns the number of files changed."""
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import names
    forward = names._maps()[0]
    changed = 0
    for path in sorted(output.glob('*.c')) + sorted(output.glob('*.s')):
        text = path.read_text(encoding='latin-1')
        new = names.WORDS.sub(lambda m: forward.get(m[0], m[0]), text)
        if new != text:
            path.write_text(new, encoding='latin-1', newline='\n')
            changed += 1
    return changed


